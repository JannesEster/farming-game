#!/usr/bin/env python3
"""Copy sprites-v2/final into public/sprites/v2, sized for the zoom we actually draw."""

import json
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = Path("/cursor/stores/bot/farming-game/sprites-v2")
DST = ROOT / "public" / "sprites" / "v2"
DOCS = ROOT / "docs" / "reference" / "art-v2"
MANIFEST_TS = ROOT / "src" / "render" / "v2Manifest.ts"

# Largest edge we need at zoom 2 with a little sharpness headroom.
MAX_EDGE = {
    "ground-tile": 512,
    "cattle": 150,
    "person": 150,
    "vegetation": 210,
    "terrain": 180,
    "fence": 200,
    "yard": 210,
    "prop": 220,
    "building": 300,
    "vehicle": 480,
}
COLORS = {
    "ground-tile": 96,
    "cattle": 72,
    "person": 72,
    "vehicle": 96,
}


def quantize(image: Image.Image, colors: int) -> Image.Image:
    rgba = image.convert("RGBA")
    alpha = rgba.getchannel("A")
    reduced = rgba.convert("RGB").quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    out = reduced.convert("RGBA")
    out.putalpha(alpha)
    return out


def punch_bakkie(image: Image.Image) -> Image.Image:
    """Drop the faint grey-blue patch under the bakkie. A code shadow replaces it."""
    image = image.convert("RGBA")
    pixels = image.load()
    width, height = image.size
    y0 = int(height * 0.72)
    removed = 0
    opaque = 0
    for y in range(height):
        for x in range(width):
            r, g, b, a = pixels[x, y]
            if a < 8:
                continue
            opaque += 1
            if y < y0:
                continue
            spread = max(r, g, b) - min(r, g, b)
            grey_blue = b > r + 4 and b + 6 >= g and spread < 42 and r < 160
            if grey_blue:
                pixels[x, y] = (r, g, b, 0)
                removed += 1
    print(f"  bakkie punch removed {removed} of {opaque} opaque px")
    return image


def target_edge(category: str, width: int, height: int) -> int:
    cap = MAX_EDGE.get(category, 200)
    if category == "vehicle" and max(width, height) < 500:
        cap = 240
    return cap


def main() -> None:
    manifest = json.loads((SRC / "final" / "manifest.json").read_text())
    if DST.exists():
        shutil.rmtree(DST)
    DST.mkdir(parents=True)
    DOCS.mkdir(parents=True)
    for ref in (SRC / "refs").iterdir():
        if ref.suffix.lower() == ".png":
            shutil.copy2(ref, DOCS / ref.name)
    shutil.copy2(SRC / "README.md", DOCS / "README.md")
    contact = SRC / "final" / "contact-sheet.png"
    if contact.exists():
        shutil.copy2(contact, DOCS / "contact-sheet.png")

    entries = []
    total = 0
    for sprite in manifest["sprites"]:
        src = SRC / "final" / sprite["file"]
        image = Image.open(src).convert("RGBA")
        if sprite["file"].startswith("vehicle-bakkie"):
            image = punch_bakkie(image)
        cap = target_edge(sprite["category"], image.width, image.height)
        long_edge = max(image.width, image.height)
        if long_edge > cap:
            scale = cap / long_edge
            image = image.resize(
                (max(1, round(image.width * scale)), max(1, round(image.height * scale))),
                Image.Resampling.LANCZOS,
            )
        colors = COLORS.get(sprite["category"], 80)
        if sprite["category"] != "ground-tile":
            image = quantize(image, colors)
        else:
            image = quantize(image, colors)
        out = DST / sprite["file"]
        image.save(out, format="PNG", optimize=True)
        size = out.stat().st_size
        total += size
        anchor = sprite.get("anchor") or {"x": 0.5, "y": 0.5}
        entries.append(
            {
                "file": sprite["file"],
                "key": "v2-" + sprite["file"].removesuffix(".png"),
                "category": sprite["category"],
                "facing": sprite.get("facing"),
                "width": image.width,
                "height": image.height,
                "sourceWidth": sprite["width"],
                "sourceHeight": sprite["height"],
                "anchorX": round(float(anchor["x"]), 4),
                "anchorY": round(float(anchor["y"]), 4),
            }
        )
        print(f"{sprite['file']:42} {image.width:4}x{image.height:<4} {size/1024:7.1f} KB")

    lines = [
        "/* Generated by scripts/optimize-v2-sprites.py. Anchors are 0–1 foot points. */",
        "export type V2SpriteMeta = {",
        "  file: string;",
        "  key: string;",
        "  category: string;",
        "  facing: string | null;",
        "  width: number;",
        "  height: number;",
        "  sourceWidth: number;",
        "  sourceHeight: number;",
        "  anchorX: number;",
        "  anchorY: number;",
        "};",
        "",
        "export const V2_SPRITES: readonly V2SpriteMeta[] = [",
    ]
    for entry in entries:
        facing = "null" if entry["facing"] is None else json.dumps(entry["facing"])
        lines.append(
            "  {"
            + f" file: {json.dumps(entry['file'])}, key: {json.dumps(entry['key'])},"
            + f" category: {json.dumps(entry['category'])}, facing: {facing},"
            + f" width: {entry['width']}, height: {entry['height']},"
            + f" sourceWidth: {entry['sourceWidth']}, sourceHeight: {entry['sourceHeight']},"
            + f" anchorX: {entry['anchorX']}, anchorY: {entry['anchorY']} }},"
        )
    lines.append("];")
    lines.append("")
    MANIFEST_TS.write_text("\n".join(lines))
    print(f"TOTAL {total/1e6:.2f} MB  sprites {len(entries)}")
    if total > 8_000_000:
        raise SystemExit("sprite pack is over 8 MB")


if __name__ == "__main__":
    main()
